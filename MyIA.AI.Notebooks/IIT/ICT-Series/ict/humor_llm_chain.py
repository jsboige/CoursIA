def taxonomy_labels() -> tuple[str, ...]:
    """Taxonomie canonique, lue chez l'organe du banc (jamais recopiee ici).

    Le vecu de la taxonomie est dans ``GameTheory/humour_banc/organ.py`` ;
    ``ict.humor_pairs`` en re-expose la constante. Lire la source evite
    qu'une derivation de taxonomie ne drift dans le present module.
    """
    from .humor_pairs import LABELS

    return tuple(LABELS)


class RubricEntry:
    """Une categorie de la taxonomie et sa definition operationnelle.

    Les definitions sont une **reformulation** des regles des detecteurs du
    banc (``GameTheory-18c``, cellules 4 et 6 : le rire est un stimulus, le
    partage de forme est la grandeur ; le refus signale le cas 5).
    """

    __slots__ = ("description", "label")

    def __init__(self, label: str, description: str) -> None:
        self.label = label
        self.description = description

    def __repr__(self) -> str:  # pragma: no cover - confort de lecture
        return f"RubricEntry({self.label!r})"

    def __eq__(self, other: object) -> bool:
        if not isinstance(other, RubricEntry):
            return NotImplemented
        return self.label == other.label and self.description == other.description

    def as_dict(self) -> dict[str, str]:
        return {"label": self.label, "description": self.description}


#: Descriptions operationnelles, une par categorie de la taxonomie.
#:
#: Version 2 — correction d'une **definition** et non d'un modele. La version 1
#: exigeait un « marqueur de rire explicite » pour ``humour_reussi`` et
#: ``rire_sans_recadrage``. Verification a la source sur le corpus committe :
#: **aucune** des 30 blagues manuelles (`blague-manuelle`, etiquette
#: `humour_reussi`) ni des 3 edge cases `rire_sans_recadrage` ne porte un
#: marqueur de rire litteral (mesure : 0/33 sur `haha|heh|hihihi|lol|xd`) ; le
#: rire y est **rapporte** (« elle a ri aux eclats ») ou **vise** (la blague
#: en une ligne est construite pour faire rire, sans que personne n'ecrive
#: « haha »). La taxonomie source ne repose donc sur aucun marqueur : son
#: fond est l'**effet communicationnel** (rire x recadrage x uptake x refus).
#: Une rubrique qui exige un marqueur absente du corpus rend ``humour_reussi``
#: inatteignable et ecrase tout le banc vers « rien » : le desaccord mesure
#: etait un desaccord de definition, pas une erreur du modele.
_DESCRIPTIONS: Mapping[str, str] = {
    "humour_reussi": (
        "le texte est construit pour faire rire (jeu de mots, double lecture, "
        "chute) ET il installe un renversement de cadre que le destinataire "
        "adopte : la forme est partagee (le destinataire ri, et le point ne "
        "se comprend qu'en changeant de cadre). Le destinataire peut etre "
        "l'interlocuteur ou le lecteur ; aucun marqueur de rire n'est "
        "necessaire, la blague en une ligne en est l'exemple type"
    ),
    "rire_sans_recadrage": (
        "le rire est present — marque ou rapporte (« elle a ri aux eclats », "
        "« haha ») — mais aucun renversement de cadre : on rit d'un stimulus, "
        "d'une situation ou d'une contagion de rire, l'echange ne change pas "
        "de cadre"
    ),
    "recadrage_sans_rire": (
        "un renversement de cadre est present (double lecture, callback, "
        "anachronisme, inversion, chute seche) mais le rire ne l'est pas : la "
        "forme est comprise, sans effet comique"
    ),
    "offensif_compris_non_partage": (
        "le jeu ou la pique est percu (il est entendu, vu, compris) mais l'un "
        "des agents refuse d'y jouer : « j'ai entendu la blague, j'ai pas "
        "ri », « j'ai souri poliment » ; le refus est explicite"
    ),
    "rien": (
        "ni rire ni renversement : le texte est une declaration factuelle, "
        "une phrase courante, un recit ou un expose"
    ),
}


def build_rubric() -> tuple[RubricEntry, ...]:
    """Rubric dans l'ordre canonique de la taxonomie."""
    return tuple(
        RubricEntry(label, _DESCRIPTIONS[label]) for label in taxonomy_labels()
    )


def build_rubric_reversed() -> tuple[RubricEntry, ...]:
    """Rubric dans l'ordre inverse : la variante de relecture du controle.

    L'inversion n'est pas un cosmetique : elle casse la position de la
    categorie positive dans la liste, qui est le levier le plus court sur
    un modele qui suit l'ordre de presentation.
    """
    return tuple(reversed(build_rubric()))


