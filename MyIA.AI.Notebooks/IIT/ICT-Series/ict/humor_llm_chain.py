# -*- coding: utf-8 -*-
"""Chaine d'etiquetage humour par LLM local -- tracee, controle, provenance (#26911).

Ce module est le **producteur** d'une campagne d'annotation humour par un LLM
**local** (endpoint OpenAI-compatible, ici le vLLM de la flotte). Il ne
calcule aucun accord : la mesure est faite par l'instrument existant
``ict/humor_agreement.py`` (kappa de Cohen, bande du hasard, cout en tokens),
que ce module **consomme** -- les enregistrements qu'il produit sont ecrits
dans le format JSONL que cet instrument lit.

Trois exigences de l'issue #26911 (etape 2) sont portees ici :

1. **Chaque etape est tracee** : version du prompt, modele **serti** (tel que
   l'endpoint le renvoie), parametres de generation, graine. La trace est
   ecrite a cote des annotations, jamais deduite apres coup.
2. **Un echantillon de controle est relu independamment** : la variante
   ``controle`` inverse l'ordre de presentation des categories et reformule
   la regle de departage. L'accord mesure entre les deux passes est un
   **auto-accord intra-modele** (relecture independante du prompt), pas un
   accord inter-annotateurs : le dire serait une surinterprétation. L'accord
   inter-annotateurs, lui, est mesure contre la **reference commitee** du
   depot, via ``agreement_report(reference=...)``.
3. **Les donnees augmentees sont marquees et jamais melangees au jeu
   d'evaluation** : toute paraphrase generee par le modele porte
   ``source="augmented"`` et ``in_evaluation_set=False``, et
   :func:`build_evaluation_set` **refuse** un lot qui viole cette regle
   (l'invariant est teste, pas seulement documente).

Perimetre et non-duplication (regle organ-first) :

* la **taxonomie** (cinq categories d'effet communicationnel) n'est pas
  recopiee : elle est lue chez l'organe du banc
  (``GameTheory/humour_banc/organ.py``, re-exposee par
  ``ict.humor_pairs.LABELS``) ;
* le **detecteur LLM** du banc (cellule 26 de ``GameTheory-18c``, canal
  OpenRouter epingle, ``anthropic/claude-haiku-4.5``) reste le detecteur du
  banc : ce module n'en est pas une reecriture, c'est un **driver de
  campagne** vers un autre canal (le LLM local de la flotte, sans cle
  externe) qui produit le format d'enregistrement attendu par
  ``ict/humor_agreement.py`` ;
* la **mesure** n'est pas reimplementee : ce module appelle
  ``ict.humor_agreement`` pour ecrire et pour rapporter.

Contraintes d'env : stdlib uniquement (``urllib``) pour l'appel HTTP, afin de
ne pas introduire de dependance pip dans le coeur du package ``ict/`` (le
package est numpy-only et s'installe sous Python 3.9). Aucune cle n'est
codee en dur : la cle du endpoint local est lue dans un fichier ``.env`` a
l'execution, jamais dans le depot.
"""
