def _item_text(item: Mapping[str, Any]) -> str:
    """Texte d'un item : champ ``texte`` (banc) ou ``text`` (corpus etranger)."""
    if "texte" in item:
        return str(item["texte"])
    return str(item["text"])


def _map_label(
    annotator: LocalLLMAnnotator,
    items: Sequence[Mapping[str, Any]],
    variant: str,
    workers: int,
) -> list[dict[str, Any]]:
    """Etiquette les items, en serie ou en lot (resultats dans l'ordre)."""
    if workers <= 1:
        return [annotator.label(_item_text(item), variant=variant) for item in items]
    from concurrent.futures import ThreadPoolExecutor

    with ThreadPoolExecutor(max_workers=workers) as pool:
        return list(
            pool.map(
                lambda item: annotator.label(_item_text(item), variant=variant),
                items,
            )
        )


def _map_augment(
    annotator: LocalLLMAnnotator,
    items: Sequence[Mapping[str, Any]],
    workers: int,
) -> list[dict[str, Any]]:
    """Paraphrase les items, en serie ou en lot (resultats dans l'ordre)."""
    if workers <= 1:
        return [annotator.augment(_item_text(item)) for item in items]
    from concurrent.futures import ThreadPoolExecutor

    with ThreadPoolExecutor(max_workers=workers) as pool:
        return list(
            pool.map(lambda item: annotator.augment(_item_text(item)), items)
        )


def annotate_items(
    items: Sequence[Mapping[str, Any]],
    annotator: LocalLLMAnnotator,
    *,
    annotator_name: str,
    variant: str = "principal",
    corpus: str = "",
    source: str = SOURCE_REAL,
    in_evaluation_set: bool = True,
    label_of: Callable[[Mapping[str, Any]], str] | None = None,
    workers: int = 1,
) -> list[dict[str, Any]]:
    """Etiquette une liste d'items et retourne les enregistrements JSONL.

    Chaque enregistrement est directement lisible par
    ``ict.humor_agreement.read_annotations_jsonl`` : les champs de mesure
    (``id``, ``annotator``, ``label``, ``prompt_tokens``,
    ``completion_tokens``) y sont, la provenance y est ajoutee.

    ``workers > 1`` parallelise les appels HTTP (le endpoint local les
    sert en lot) ; l'ordre des enregistrements suit l'ordre des items, donc
    la sortie ne depend pas de l'ordre d'arrivee des reponses.
    """
    results = _map_label(annotator, items, variant, workers)
    records: list[dict[str, Any]] = []
    for item, result in zip(items, results):
        item_id = str(item["id"])
        record = {
            "id": item_id,
            "annotator": annotator_name,
            "label": result["label"],
            "prompt_tokens": result["prompt_tokens"],
            "completion_tokens": result["completion_tokens"],
            "corpus": corpus,
            "source": source,
            "in_evaluation_set": bool(in_evaluation_set),
            "prompt_version": result["prompt_version"],
            "served_model": result["served_model"],
            "variant": result["variant"],
            "seed": result["seed"],
            "temperature": result["temperature"],
            "top_p": result["top_p"],
            "max_tokens": result["max_tokens"],
            "attempts": result.get("attempts", 1),
            "raison": result["raison"],
        }
        if label_of is not None:
            record["reference_label"] = label_of(item)
        records.append(record)
    return records


def augment_items(
    items: Sequence[Mapping[str, Any]],
    annotator: LocalLLMAnnotator,
    *,
    annotator_name: str,
    corpus: str = "",
    workers: int = 1,
) -> list[dict[str, Any]]:
    """Genere les paraphrases (donnees augmentees) d'une liste d'items.

    Chaque enregistrement porte ``source="augmented"`` et
    ``in_evaluation_set=False`` : c'est la source de verite du marquage, pas
    une convention de lecture.
    """
    results = _map_augment(annotator, items, workers)
    records: list[dict[str, Any]] = []
    for item, result in zip(items, results):
        item_id = str(item["id"])
        records.append(
            {
                "id": f"{item_id}::aug",
                "annotator": annotator_name,
                "label": "augmentation",
                "prompt_tokens": result["prompt_tokens"],
                "completion_tokens": result["completion_tokens"],
                "corpus": corpus,
                "source": SOURCE_AUGMENTED,
                "in_evaluation_set": False,
                "prompt_version": result["prompt_version"],
                "served_model": result["served_model"],
                "seed": result["seed"],
                "parent_id": item_id,
                "texte": result["paraphrase"],
            }
        )
    return records


def validate_provenance(records: Iterable[Mapping[str, Any]]) -> None:
    """Verifie le contrat de provenance de chaque enregistrement.

    Leve ``ValueError`` si un champ manque, si la source est inconnue, ou
    si un item augmente se declare dans le jeu d'evaluation.
    """
    for record in records:
        for field in ("id", "annotator", "label", "source", "in_evaluation_set"):
            if field not in record:
                raise ValueError(f"champ {field!r} manquant sur {record.get('id')!r}")
        source = record["source"]
        if source not in SOURCES:
            raise ValueError(f"source inconnue {source!r} sur {record.get('id')!r}")
        if source == SOURCE_AUGMENTED and record["in_evaluation_set"]:
            raise ValueError(
                f"item augmente declare dans le jeu d'evaluation : {record.get('id')!r}"
            )


def build_evaluation_set(records: Iterable[Mapping[str, Any]]) -> list[dict[str, Any]]:
    """Retourne le jeu d'evaluation, **refusant** tout item augmente.

    L'invariant de #26911 est ici un code, pas une phrase : un lot qui
    melange une donnee augmentee au jeu d'evaluation leve au lieu de
    produire un resultatSilentement faux.
    """
    materialized = list(records)
    validate_provenance(materialized)
    return [dict(record) for record in materialized if record["in_evaluation_set"]]


#: Source des instances du banc dont l'etiquette de reference est posee par une
#: **heuristique de categorie** Argumentum, et non par un jugement humain du
#: texte. Ces instances sont des scenarios tronques (« ... contexte: ... ») :
#: l'etiquette y decrit une categorie metadonnee, elle n'est pas derivable du
#: texte. La lecture de la reference se fait donc par population.
ARGUMENTUM_SOURCE = "ArgumentumGames/Argumentum"


def build_evaluation_sample(
    corpus: list[dict[str, Any]],
    *,
    arg_per_label: int,
    manual_limit: int = 0,
    seed: int = DEFAULT_SEED,
) -> tuple[list[dict[str, Any]], list[dict[str, Any]], list[dict[str, Any]]]:
    """Constitue la population d'evaluation du banc.

    Le banc n'a **pas** une seule origine de label : 60 instances ``arg-*`` sont
    etiquetees par une heuristique de categorie Argumentum ; les 30 blagues
    manuelles, les 20 declarations factuelles et les 10 edge cases sont
    etiquetes a la main. L'etiquette d'une instance ``arg-*`` applique une
    categorie metadonnee (« relation intime » -> ``humour_reussi``) a un
    scenario tronque : elle n'est pas derivable du texte, donc un accord mesure
    contre elle decrit un **decalage de methode**, pas une performance.

    La population d'evaluation prend donc **tous** les items a etiquette humaine
    (la seule population ou l'accord contre la reference est interpretable) et
    un echantillon stratifie de la population heuristique (contraste).

    Rend ``(echantillon, items manuels, items heuristiques)``.
    """
    manual = [item for item in corpus if item.get("source") != ARGUMENTUM_SOURCE]
    heuristic = [item for item in corpus if item.get("source") == ARGUMENTUM_SOURCE]
    if manual_limit > 0:
        manual = manual[:manual_limit]
    stratified = sample_stratified(
        heuristic,
        label_of=lambda item: str(item["label"]),
        per_label=arg_per_label,
        seed=seed,
    )
    return manual + stratified, manual, stratified


def reference_nature(corpus: list[dict[str, Any]]) -> dict[str, Any]:
    """Origine de l'etiquette de reference, **lue dans le corpus lui-meme**.

    Chaque instance porte une justification ; celle des instances ``arg-*``
    nomme explicitement l'heuristique qui a produit l'etiquette (« categorie
    X -> heuristique cell[30] donne Y »). Le rapport publie donc l'origine
    depuis la source, et non depuis une lecture de notre part.
    """
    buckets: dict[str, list[str]] = {}
    for item in corpus:
        justification = str(item.get("justification", ""))
        nature = (
            "heuristique-declaree"
            if "heuristique" in justification.lower()
            else "jugement-manuel"
        )
        buckets.setdefault(nature, []).append(str(item["id"]))
    return {
        nature: {"n": len(ids), "ids": sorted(ids)}
        for nature, ids in sorted(buckets.items())
    }


def sample_composition(sample: Sequence[Mapping[str, Any]]) -> dict[str, int]:
    """Composition d'un echantillon, lue sur la **source** de chaque item.

    Renvoie le compte par origine d'etiquette de reference : c'est la
    repartition qui rend l'accord interpretable ou non (une etiquette
    heuristique sur un scenario tronque n'est pas derivable du texte).
    """
    return {
        "jugement-humain": sum(
            1 for item in sample if item.get("source") != ARGUMENTUM_SOURCE
        ),
        "heuristique-argumentum": sum(
            1 for item in sample if item.get("source") == ARGUMENTUM_SOURCE
        ),
    }


def sample_stratified(
    items: Sequence[Mapping[str, Any]],
    *,
    label_of: Callable[[Mapping[str, Any]], str],
    per_label: int,
    seed: int,
) -> list[dict[str, Any]]:
    """Echantillon deterministe et stratifie par label.

    Le tirage est reproductible (graine explicite) et l'echantillon garde la
    proportion des labels : sans cela, un echantillon tire au hasard peut
    ne pas couvrir les classes rares, et l'accord mesure ne dit plus rien.
    """
    buckets: dict[str, list[Mapping[str, Any]]] = {}
    for item in items:
        buckets.setdefault(label_of(item), []).append(item)
    rng = random.Random(seed)
    chosen: list[dict[str, Any]] = []
    for label in sorted(buckets):
        pool = list(buckets[label])
        rng.shuffle(pool)
        chosen.extend(dict(item) for item in pool[:per_label])
    return chosen


