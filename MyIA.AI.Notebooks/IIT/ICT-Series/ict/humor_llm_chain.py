def read_env_value(path: str | Path, key: str) -> str | None:
    """Lit ``key`` dans un fichier ``.env`` ; ``None`` si absent ou vide.

    Lecture naive et explicite (``KEY=valeur``), suffisante pour le
    ``.env`` de la stack GenAI de la machine. La valeur n'est jamais
    journalisee ni retournee a l'appelant par un autre chemin.
    """
    env_path = Path(path)
    if not env_path.is_file():
        return None
    for raw_line in env_path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        name, _, value = line.partition("=")
        if name.strip() != key:
            continue
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in ("'", '"'):
            value = value[1:-1]
        return value or None
    return None


