class LocalLLMAnnotator:
    """Client d'un endpoint OpenAI-compatible local, avec sortie structuree.

    Le client n'invente aucun repli : si le endpoint ne repond pas, l'appel
    leve. Un degrade silencieux (etiquette par defaut, texte vide) rendrait
    la campagne inexploitable sans le dire.
    """

    def __init__(
        self,
        *,
        base_url: str = DEFAULT_BASE_URL,
        model: str = DEFAULT_MODEL,
        api_key: str | None = None,
        seed: int = DEFAULT_SEED,
        temperature: float = DEFAULT_TEMPERATURE,
        top_p: float = DEFAULT_TOP_P,
        max_tokens: int = DEFAULT_MAX_TOKENS,
        timeout: float = DEFAULT_TIMEOUT,
        prompt_version: str = PROMPT_VERSION,
    ) -> None:
        self.base_url = base_url.rstrip("/")
        self.model = model
        self.api_key = api_key
        self.seed = seed
        self.temperature = temperature
        self.top_p = top_p
        self.max_tokens = max_tokens
        self.timeout = timeout
        self.prompt_version = prompt_version

    # -- trace ------------------------------------------------------------ #

    def trace(self) -> dict[str, Any]:
        """Trace des parametres de la chaine (sans la cle)."""
        return {
            "base_url": self.base_url,
            "model_asked": self.model,
            "prompt_version": self.prompt_version,
            "seed": self.seed,
            "temperature": self.temperature,
            "top_p": self.top_p,
            "max_tokens": self.max_tokens,
            "timeout": self.timeout,
        }

    # -- appel HTTP ------------------------------------------------------- #

    def _post(self, payload: Mapping[str, Any]) -> dict[str, Any]:
        url = f"{self.base_url}/chat/completions"
        request = urllib.request.Request(
            url,
            data=json.dumps(payload).encode("utf-8"),
            method="POST",
        )
        request.add_header("Content-Type", "application/json")
        if self.api_key:
            request.add_header("Authorization", f"Bearer {self.api_key}")
        try:
            with urllib.request.urlopen(request, timeout=self.timeout) as response:
                return json.loads(response.read().decode("utf-8"))
        except urllib.error.HTTPError as exc:  # pragma: no cover - reseau
            detail = exc.read().decode("utf-8", "replace")[:400]
            raise RuntimeError(f"endpoint {url} : HTTP {exc.code} — {detail}") from exc
        except urllib.error.URLError as exc:  # pragma: no cover - reseau
            raise RuntimeError(f"endpoint {url} injoignable : {exc.reason}") from exc

    # -- labeling --------------------------------------------------------- #

    def label(
        self,
        text: str,
        *,
        variant: str = "principal",
        max_attempts: int = 3,
    ) -> dict[str, Any]:
        """Etiquette un texte ; retourne la reponse tracee.

        Retourne un dict : ``label``, ``raison``, ``served_model`` (tel que
        l'endpoint le declare -- c'est le **nom servi**, pas le nom demande),
        ``prompt_tokens``, ``completion_tokens``, ``attempts`` et les
        parametres.

        Un modele qui epuise son budget de tokens peut renvoyer un message
        **vide** (``content=None``) : l'appel est alors rejoue avec un
        budget double, et le nombre de tentatives est trace. Un item qui
        echoue apres ``max_attempts`` leve : un etiquetage par defaut
        rendrait la campagne silencieusement fausse.
        """
        rubric = build_rubric_reversed() if variant == "controle" else build_rubric()
        prompt = build_prompt(text, rubric=rubric, variant=variant)
        budget = self.max_tokens
        last_error: str = ""
        for attempt in range(1, max_attempts + 1):
            payload = {
                "model": self.model,
                "messages": [{"role": "user", "content": prompt}],
                "temperature": self.temperature,
                "top_p": self.top_p,
                "max_tokens": budget,
                "seed": self.seed,
                "response_format": _response_schema([entry.label for entry in rubric]),
            }
            raw = self._post(payload)
            choices = raw.get("choices") or []
            if not choices:
                last_error = f"reponse sans choix : {json.dumps(raw)[:300]}"
                budget *= 2
                continue
            message = choices[0].get("message") or {}
            content = message.get("content")
            if content is None or not str(content).strip():
                reasoning = message.get("reasoning") or ""
                last_error = (
                    "message vide (budget de tokens epuise "
                    f"avant la reponse : finish_reason="
                    f"{choices[0].get('finish_reason')!r}, raisonnement={len(reasoning)} car)"
                )
                budget *= 2
                continue
            try:
                parsed = json.loads(content)
            except json.JSONDecodeError as exc:
                last_error = f"sortie non JSON du modele : {str(content)[:300]!r}"
                budget *= 2
                continue
            label = parsed.get("label")
            allowed = [entry.label for entry in rubric]
            if label not in allowed:
                raise RuntimeError(
                    f"etiquette hors taxonomie : {label!r} (autorisees : {allowed})"
                )
            usage = raw.get("usage") or {}
            return {
                "label": label,
                "raison": parsed.get("raison", ""),
                "served_model": raw.get("model", ""),
                "prompt_tokens": int(usage.get("prompt_tokens", 0) or 0),
                "completion_tokens": int(usage.get("completion_tokens", 0) or 0),
                "prompt_version": self.prompt_version,
                "variant": variant,
                "seed": self.seed,
                "temperature": self.temperature,
                "top_p": self.top_p,
                "max_tokens": budget,
                "attempts": attempt,
            }
        raise RuntimeError(
            f"etiquetage impossible apres {max_attempts} tentatives : {last_error}"
        )

    # -- augmentation ----------------------------------------------------- #

    def augment(self, text: str) -> dict[str, Any]:
        """Genere une paraphrase d'un texte (donnee **augmentee**).

        Le retour porte ``source="augmented"`` : la paraphrase est une
        production du modele, jamais un item de corpus. Elle ne peut pas
        entrer dans un jeu d'evaluation (invariant verifie par
        :func:`build_evaluation_set`).
        """
        prompt = (
            "Reecris ce texte court dans d'autres mots, en gardant exactement "
            "le meme sens et le meme registre. Reponds uniquement par le JSON "
            "demande.\n\n"
            f"Texte :\n\"\"\"{text}\"\"\""
        )
        payload = {
            "model": self.model,
            "messages": [{"role": "user", "content": prompt}],
            "temperature": self.temperature,
            "top_p": self.top_p,
            "max_tokens": self.max_tokens,
            "seed": self.seed,
            "response_format": {
                "type": "json_schema",
                "json_schema": {
                    "name": "humour_paraphrase",
                    "strict": True,
                    "schema": {
                        "type": "object",
                        "properties": {"paraphrase": {"type": "string"}},
                        "required": ["paraphrase"],
                        "additionalProperties": False,
                    },
                },
            },
        }
        raw = self._post(payload)
        choices = raw.get("choices") or []
        if not choices:
            raise RuntimeError(f"reponse sans choix : {json.dumps(raw)[:400]}")
        message = choices[0].get("message") or {}
        content = message.get("content")
        if content is None or not str(content).strip():
            raise RuntimeError(
                "paraphrase vide : budget de tokens epuise avant la reponse "
                f"(finish_reason={choices[0].get('finish_reason')!r})"
            )
        try:
            parsed = json.loads(content)
        except json.JSONDecodeError as exc:
            raise RuntimeError(f"sortie non JSON du modele : {str(content)[:300]!r}") from exc
        usage = raw.get("usage") or {}
        return {
            "paraphrase": parsed.get("paraphrase", ""),
            "served_model": raw.get("model", ""),
            "prompt_tokens": int(usage.get("prompt_tokens", 0) or 0),
            "completion_tokens": int(usage.get("completion_tokens", 0) or 0),
            "prompt_version": self.prompt_version,
            "seed": self.seed,
            "source": SOURCE_AUGMENTED,
        }


